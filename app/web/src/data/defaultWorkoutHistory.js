import { createId } from "../core/uid.js";

function createSet(config) {
  return {
    exerciseId: config.exerciseId ?? "",
    setNumber: config.setNumber,
    status: config.status ?? "completed",
    actualReps: config.actualReps ?? null,
    actualDurationSec: config.actualDurationSec ?? null,
    actualWeightKg: config.actualWeightKg ?? null,
    actualResistance: config.actualResistance ?? null,
  };
}

function createWorkout(config) {
  return {
    id: createId("workout"),
    activePlanId: config.activePlanId ?? null,
    activePlanVersion: config.activePlanVersion ?? "1.0",
    routineId: config.routineId ?? null,
    stageId: config.stageId ?? null,
    startedAt: config.startedAt,
    completedAt: config.completedAt,
    sets: config.sets.map(createSet),
  };
}

